<#
  blocks/build.ps1 — generate mountable archetype blocks from one source of truth.

  WHY THIS EXISTS
  The monolithic sampler proves zg.css + motion.js are good. It does NOT prove
  that the markup snippet someone pastes into a live video is the same markup we
  tested — the sampler keeps its own copy. This generator removes the copy: every
  archetype's canonical markup lives in blocks/<name>/<name>.src.html, and the
  build inlines the shared zg.css + type.js + icons.js + motion.js around it to
  produce blocks/<name>/<name>.html — a HyperFrames sub-composition the sampler
  AND every live video mount via data-composition-src. Same bytes everywhere.

  WHAT A .src.html LOOKS LIKE
    <!--zg
    { "id":"lens", "duration":6, "camClass":"cam dense",
      "variables":[
        {"id":"caption","type":"string","label":"Sub caption","default":"Never an empty glass."}
      ] }
    zg-->
    <div class="lenswrap"> ... archetype markup, exactly as in the sampler ... </div>
    <div class="sub" data-anim="fi" data-at="3.3" data-var-text="caption">Never an empty glass.</div>

  The markup is whatever sits inside <div class="cam"> in the sampler section.
  data-var-text / data-var-src bindings (see hyperframes-core variables) let a
  live video pass its own words via data-variable-values on the host slot.

  USAGE
    .\build.ps1                 # rebuild every block
    .\build.ps1 lens funnel     # rebuild only these
    .\build.ps1 -NoMirror       # skip the _frames/blocks/ promoted copy

  Re-run after ANY edit to zg.css / motion.js / icons.js / type.js / a .src.html.
  Zero tokens. Pure text assembly.
#>
param(
  [Parameter(ValueFromRemainingArguments = $true)] [string[]] $Only,
  [switch] $NoMirror
)

$ErrorActionPreference = "Stop"
Set-Location -Path $PSScriptRoot          # blocks/
$repo   = Split-Path $PSScriptRoot -Parent # zg-frames/
$mirror = Join-Path (Split-Path $repo -Parent) "blocks"  # _frames/blocks/

$css = Get-Content (Join-Path $repo "zg.css") -Raw
# Replace zg.css's path-based @font-face with base64 data: URIs. A mounted
# sub-comp renders isolated, so neither a host @font-face nor a relative
# url("fonts/...") reaches it reliably; an embedded data: URI has no path to
# resolve. _fontface.css is generated by make-fontface.ps1.
$fontFace = Get-Content (Join-Path $PSScriptRoot "_fontface.css") -Raw
$css = [regex]::Replace($css, '(?m)^@font-face\{[^}]*\}\r?\n?', '')
$css = $fontFace + "`n" + $css

function InlineJs($path) {
  # a literal </script> inside a JS comment or string still closes the HTML tag —
  # break it so the inlined script survives (valid JS, identical behaviour)
  (Get-Content $path -Raw).Replace('</script', '<\/script')
}
$typeJs  = InlineJs (Join-Path $repo "type.js")
$iconsJs = InlineJs (Join-Path $repo "icons.js")
$motionJs= InlineJs (Join-Path $repo "motion.js")

$dirs = Get-ChildItem -Directory | Where-Object { Test-Path (Join-Path $_.FullName "$($_.Name).src.html") }
if ($Only) { $dirs = $dirs | Where-Object { $Only -contains $_.Name } }
if (-not $dirs) { Write-Warning "No matching block sources under $PSScriptRoot"; exit 1 }

$built = @()
foreach ($d in $dirs) {
  $name = $d.Name
  $src  = Get-Content (Join-Path $d.FullName "$name.src.html") -Raw

  $m = [regex]::Match($src, '(?s)<!--zg\s*(?<j>.*?)\s*zg-->')
  if (-not $m.Success) { throw "$name.src.html: missing <!--zg { ... } zg--> meta header" }
  $meta = $m.Groups['j'].Value | ConvertFrom-Json
  $markup = $src.Substring($m.Index + $m.Length).Trim()

  $id  = if ($meta.id) { $meta.id } else { $name }
  $dur = [double]$meta.duration
  $cam = if ($meta.camClass) { $meta.camClass } else { "cam" }
  $secEnd = if ($meta.sectionEnd) { " data-section-end" } else { "" }
  $varsJson = if ($meta.variables) { ($meta.variables | ConvertTo-Json -Compress -Depth 6) } else { "[]" }
  if ($varsJson -notlike '`[*') { $varsJson = "[$varsJson]" }  # ConvertTo-Json drops the array wrapper for a single item

  # <template> transport shape (references/sub-compositions.md). The current
  # runtime only samples/validates a mounted block in this shape; the older
  # no-template registry shape (data-chart) renders but the check can't see it.
  # Known trade-off: a mounted block composites ~3-4% larger than the same scene
  # inline in the monolith. Uniform across all 39, every downstream video
  # inherits it consistently — it is a framing change to approve once, not a
  # per-scene regression. Root cause not found; see STATUS.md.
  $html = @"
<!doctype html>
<html lang="en" data-resolution="landscape" data-composition-variables='$varsJson'>
<head><meta charset="UTF-8"/></head>
<body>
<template>
<style>
$css
#root{position:absolute;inset:0;font-family:"Open Sans",system-ui,sans-serif}
</style>
<div id="root" data-composition-id="$id" data-width="1920" data-height="1080" data-start="0" data-duration="600">
<div class="g1" data-layout-allow-overflow></div><div class="g2" data-layout-allow-overflow></div><div class="grid"></div>
<section id="$id-sc" class="clip" data-start="0" data-duration="600" data-scene-dur="$dur" data-track-index="1"$secEnd><div class="$cam">
$markup
</div></section>
</div>
<script>
$typeJs
</script>
<script>
$iconsJs
</script>
<script>
$motionJs
</script>
<script>
(function(){
  /* THIS instance's root, not the first on the page — a live video mounts the
     same archetype many times, and document.querySelector would give them all
     instance 1's DOM. currentScript.closest walks up to our own subtree. */
  var s = document.currentScript;
  var root = (s && s.closest && s.closest('[data-composition-id="$id"]'))
    || document.querySelector('[data-composition-id="$id"]');
  window.ZG.buildIn(root, "$id");
})();
</script>
</template>
</body>
</html>
"@

  $utf8 = New-Object System.Text.UTF8Encoding($false)   # no BOM: DOMParser chokes on it
  [System.IO.File]::WriteAllText((Join-Path $d.FullName "$name.html"), $html, $utf8)
  if (-not $NoMirror) {
    $mDir = Join-Path $mirror $name
    New-Item -ItemType Directory -Force -Path $mDir | Out-Null
    Copy-Item (Join-Path $d.FullName "$name.src.html") (Join-Path $mDir "$name.src.html") -Force
    [System.IO.File]::WriteAllText((Join-Path $mDir "$name.html"), $html, $utf8)
  }
  $built += $name
  Write-Host ("built  {0}  (id={1}, {2}s, {3} vars)" -f $name, $id, $dur, ($meta.variables | Measure-Object).Count)
}

Write-Host ""
Write-Host ("{0} block(s) generated: {1}" -f $built.Count, ($built -join ", ")) -ForegroundColor Green
if (-not $NoMirror) { Write-Host ("mirrored to {0}" -f $mirror) -ForegroundColor DarkGray }
