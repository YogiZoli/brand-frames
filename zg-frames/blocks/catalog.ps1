<#
  blocks/catalog.ps1 — generate blocks/CATALOG.md

  The reference Opus reads when writing a live video's scene list: every
  archetype, its duration, and every variable it accepts (id, label, default).
  Regenerate after add-vars.ps1 / any meta-header change.
#>
$ErrorActionPreference = "Stop"
Set-Location -Path $PSScriptRoot

$order = @(
  "statement","display-word","hero","step-card","arrow","rail","proportion-bars","split",
  "state-flip","tiles","panel-list","countup-bars","line-chart","lens","form","contact-record",
  "progress-ring","pulse-ring","keyword-pill","end-card","overlay-lower-third","overlay-callout",
  "overlay-quote","device-footage","short-scene","library-card","highlighter","skitch-markers",
  "signature-move","branch","funnel","cycle","gauge","quote","question","before-after",
  "grid","command","lead-card"
)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# zg-frames block catalog")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("Auto-generated by ``catalog.ps1``. One archetype per section. Mount a block in a")
[void]$sb.AppendLine("live video with ``data-composition-src=""blocks/<name>/<name>.html""`` and pass the")
[void]$sb.AppendLine("variables below via ``data-variable-values`` on the slot. Timing comes from the")
[void]$sb.AppendLine("``data-sent`` anchor + ``stamp-timing.ps1``, never a hand-typed number.")
[void]$sb.AppendLine("")

foreach ($name in $order) {
  $f = Join-Path $PSScriptRoot "$name/$name.src.html"
  if (-not (Test-Path $f)) { continue }
  $m = [regex]::Match((Get-Content $f -Raw), '(?s)<!--zg\s*(?<j>.*?)\s*zg-->')
  $meta = $m.Groups['j'].Value | ConvertFrom-Json
  [void]$sb.AppendLine("## $name")
  [void]$sb.AppendLine("")
  [void]$sb.AppendLine(("duration ``{0}s`` · camClass ``{1}``{2}" -f $meta.duration, $meta.camClass,
    $(if ($meta.sectionEnd) { " · closes a section (signature ring)" } else { "" })))
  [void]$sb.AppendLine("")
  if ($meta.variables -and $meta.variables.Count -gt 0) {
    [void]$sb.AppendLine("| variable | what it is | default |")
    [void]$sb.AppendLine("|---|---|---|")
    foreach ($v in $meta.variables) {
      $def = ("{0}" -f $v.default) -replace '\|','\|'
      [void]$sb.AppendLine(("| ``{0}`` | {1} | {2} |" -f $v.id, $v.label, $def))
    }
  } else {
    [void]$sb.AppendLine("_No variables — fixed content._")
  }
  [void]$sb.AppendLine("")
}

[System.IO.File]::WriteAllText((Join-Path $PSScriptRoot "CATALOG.md"), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("wrote CATALOG.md ({0} archetypes)" -f $order.Count) -ForegroundColor Green
