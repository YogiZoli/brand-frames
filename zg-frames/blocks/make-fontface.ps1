<#
  blocks/make-fontface.ps1 — generate blocks/_fontface.css with the Open Sans
  faces as base64 data: URIs.

  Why data URIs: a mounted block's @font-face cannot survive CSS scoping, so the
  font must be declared on the MOUNT HOST. Rather than depend on the host's
  fonts/ path resolving, we embed the five weights once. ~0.8 MB, one file,
  no path resolution anywhere. assemble-sampler.mjs and the pilot host inline it.

  Re-run only if the ttf files under ../fonts/ change.
#>
$ErrorActionPreference = "Stop"
Set-Location -Path $PSScriptRoot
$fonts = Join-Path (Split-Path $PSScriptRoot -Parent) "fonts"

$weights = 400,500,600,700,800
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* generated by make-fontface.ps1 — Open Sans (brand canon), base64. Do not edit. */")
foreach ($w in $weights) {
  $ttf = Join-Path $fonts "OpenSans-$w.ttf"
  if (-not (Test-Path $ttf)) { throw "missing $ttf" }
  $b64 = [Convert]::ToBase64String([System.IO.File]::ReadAllBytes($ttf))
  [void]$sb.AppendLine("@font-face{font-family:""Open Sans"";font-weight:$w;font-display:block;src:url(data:font/ttf;base64,$b64) format(""truetype"")}")
}
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText((Join-Path $PSScriptRoot "_fontface.css"), $sb.ToString(), $utf8)
Write-Host ("wrote _fontface.css ({0:N0} KB)" -f ((Get-Item (Join-Path $PSScriptRoot "_fontface.css")).Length / 1KB)) -ForegroundColor Green
